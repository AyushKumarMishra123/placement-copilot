const AIReviewProvider = require('./AIReviewProvider');
const RuleOnlyProvider = require('./RuleOnlyProvider');

class OllamaProvider extends AIReviewProvider {
  constructor(
    baseUrl = process.env.OLLAMA_BASE_URL || 'http://localhost:11434',
    modelName = process.env.OLLAMA_MODEL || 'llama3'
  ) {
    super();
    this.baseUrl = baseUrl.replace(/\/+$/, '');
    this.modelName = modelName;
    this.fallbackProvider = new RuleOnlyProvider();
  }

  /**
   * Helper to invoke Ollama local REST API with JSON format instruction
   */
  async _callOllama(prompt, timeoutMs = 30000) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);

    try {
      const response = await fetch(`${this.baseUrl}/api/generate`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          model: this.modelName,
          prompt,
          format: 'json',
          stream: false,
          options: {
            temperature: 0.2
          }
        }),
        signal: controller.signal
      });

      if (!response.ok) {
        throw new Error(`Ollama HTTP ${response.status}: ${response.statusText}`);
      }

      const data = await response.json();
      return JSON.parse(data.response);
    } finally {
      clearTimeout(timer);
    }
  }

  async reviewResume({ parsedResume, checks, score }) {
    try {
      const failedChecks = checks
        .filter((c) => c.status === 'fail' || c.status === 'warning')
        .map((c) => ({
          id: c.id,
          name: c.name,
          status: c.status,
          evidence: c.evidence,
          currentSuggestion: c.suggestion
        }));

      const prompt = `
You are a senior technical hiring manager reviewing an undergraduate engineering student's resume for campus placements.
Return your evaluation STRICTLY as a JSON object with this exact schema:
{
  "strengths": ["string"],
  "weaknesses": ["string"],
  "recommendations": ["string"],
  "summary": "string"
}

Resume Details:
- Page Count: ${parsedResume.pageCount}
- Detected Technologies: ${JSON.stringify(parsedResume.sections?.skills?.allSkills || [])}
- Clean Text:
"""
${(parsedResume.cleanText || parsedResume.text || '').slice(0, 2000)}
"""

Failed Benchmark Checks:
${JSON.stringify(failedChecks, null, 2)}
`;

      const parsed = await this._callOllama(prompt);

      return {
        strengths: Array.isArray(parsed.strengths) ? parsed.strengths : [],
        weaknesses: Array.isArray(parsed.weaknesses) ? parsed.weaknesses : [],
        recommendations: Array.isArray(parsed.recommendations) ? parsed.recommendations : [],
        summary: parsed.summary || 'Resume analyzed via local Ollama inference.',
        provider: `ollama:${this.modelName}`
      };
    } catch (err) {
      console.warn(
        `[OllamaProvider Notice] Ollama at ${this.baseUrl} (${this.modelName}) unavailable: ${err.message}. Safely falling back to deterministic RuleOnlyProvider.`
      );
      return this.fallbackProvider.reviewResume({ parsedResume, checks, score });
    }
  }

  async generateInterviewQuestions({ targetRole, skills, projects, durationMinutes = 15, focus = 'general' }) {
    const questionCount = durationMinutes === 20 ? 6 : 4;

    try {
      const prompt = `
You are an expert technical interviewer conducting a ${durationMinutes}-minute campus placement mock interview for an engineering candidate.
Role: ${targetRole || 'Software Engineer'}
Focus: ${focus}
Candidate Skills: ${skills.join(', ')}
Candidate Projects: ${projects.map((p) => `${p.name} (${p.techStack.join(', ')})`).join('; ')}

Generate exactly ${questionCount} structured interview questions.
Return ONLY a valid JSON object matching this schema:
{
  "questions": [
    {
      "id": "q1",
      "category": "technical | project | problem_solving | behavioral",
      "prompt": "Question text here",
      "difficulty": "medium",
      "contextHint": "Why this question was chosen"
    }
  ]
}
`;

      const parsed = await this._callOllama(prompt);

      if (parsed && Array.isArray(parsed.questions) && parsed.questions.length >= 3) {
        const questions = parsed.questions.slice(0, questionCount).map((q, idx) => ({
          id: q.id || `ollama_q_${idx + 1}`,
          order: idx + 1,
          category: ['technical', 'project', 'problem_solving', 'behavioral'].includes(q.category)
            ? q.category
            : 'technical',
          prompt: q.prompt,
          difficulty: q.difficulty || 'medium',
          contextHint: q.contextHint || `Generated by Ollama for ${targetRole}`
        }));

        return {
          questions,
          planSummary: `Generated ${questions.length} questions via Ollama (${this.modelName}).`,
          provider: `ollama:${this.modelName}`
        };
      }

      throw new Error('Incomplete question list returned by Ollama');
    } catch (err) {
      console.warn(
        `[OllamaProvider Notice] Question generation fallback to RuleOnlyProvider: ${err.message}`
      );
      return this.fallbackProvider.generateInterviewQuestions({
        targetRole,
        skills,
        projects,
        durationMinutes,
        focus
      });
    }
  }

  async evaluateInterview({ targetRole, focus, questions, transcript }) {
    try {
      const prompt = `
You are evaluating a candidate's timed mock interview transcript for the role: ${targetRole} (${focus}).
Evaluate the candidate's actual answers against these 5 dimensions (scores between 0 and 100):
1. Technical Accuracy & Fundamentals (Weight 30%)
2. Project Understanding (Weight 25%)
3. Problem-Solving & Reasoning (Weight 20%)
4. Communication & Answer Structure (Weight 15%)
5. HR & Behavioral Responses (Weight 10%)

Transcript:
${JSON.stringify(
  transcript.map((t) => ({
    question: t.questionPrompt,
    category: t.category,
    answer: t.skipped ? '[Candidate skipped this question]' : t.answerText
  })),
  null,
  2
)}

Return ONLY valid JSON with this schema:
{
  "overallScore": 75,
  "dimensions": [
    { "name": "Technical Accuracy & Fundamentals", "score": 75, "weight": 30, "feedback": "string" },
    { "name": "Project Understanding", "score": 80, "weight": 25, "feedback": "string" },
    { "name": "Problem-Solving & Reasoning", "score": 70, "weight": 20, "feedback": "string" },
    { "name": "Communication & Answer Structure", "score": 75, "weight": 15, "feedback": "string" },
    { "name": "HR & Behavioral Responses", "score": 80, "weight": 10, "feedback": "string" }
  ],
  "strengths": ["string"],
  "weaknesses": ["string"],
  "recommendations": ["string"],
  "questionEvaluations": [
    { "questionId": "q1", "score": 75, "feedback": "string", "strengths": "string", "improvements": "string" }
  ]
}
`;

      const parsed = await this._callOllama(prompt, 25000);

      if (parsed && typeof parsed.overallScore === 'number' && Array.isArray(parsed.dimensions)) {
        return {
          ...parsed,
          overallScore: Math.min(100, Math.max(0, Math.round(parsed.overallScore))),
          provider: `ollama:${this.modelName}`
        };
      }

      throw new Error('Invalid evaluation structure returned by Ollama');
    } catch (err) {
      console.warn(
        `[OllamaProvider Notice] Interview evaluation fallback to RuleOnlyProvider: ${err.message}`
      );
      return this.fallbackProvider.evaluateInterview({
        targetRole,
        focus,
        questions,
        transcript
      });
    }
  }

  async reviewLinkedInProfile(context) {
    return this.fallbackProvider.reviewLinkedInProfile(context);
  }

  async evaluateCoCurricularAchievements(context) {
    return this.fallbackProvider.evaluateCoCurricularAchievements(context);
  }
}

module.exports = OllamaProvider;

